// Generate color-only overrides while keeping archived original CSS byte-for-byte.
// Product swatches (skin, hair, eyes and box colors) are deliberately excluded.
import fs from 'node:fs';
import { chromium } from '../tests/playwright-runtime.js';

const html = fs.readFileSync('dev.html', 'utf8');
const paths = [...html.matchAll(/href="(\/css\/original\/[^\"]+\.css)"/g)].map(m => m[1].slice(1));
paths.push('css/apex-shell.css');
const browser = await chromium.launch({ channel: process.env.APEX_BROWSER || 'msedge', headless: true });
try {
  const page = await browser.newPage();
  const output = await page.evaluate(sources => {
    function convert(value, property) {
      return value.replace(/#[\da-f]{3,8}\b|rgba?\([^)]+\)/gi, token => {
        let rgb, alpha;
        if (token.startsWith('#')) {
          let hex = token.slice(1);
          if (hex.length === 3 || hex.length === 4) hex = [...hex].map(c => c + c).join('');
          rgb = [0, 2, 4].map(i => parseInt(hex.slice(i, i + 2), 16));
          alpha = hex.length === 8 ? parseInt(hex.slice(6), 16) / 255 : 1;
        } else {
          const parts = token.match(/[\d.]+/g).map(Number);
          rgb = parts.slice(0, 3); alpha = parts[3] ?? 1;
        }
        const [r, g, b] = rgb.map(c => c / 255), max = Math.max(r, g, b), min = Math.min(r, g, b), delta = max - min;
        if (!delta) return token;
        const light = (max + min) / 2, saturation = delta / (1 - Math.abs(2 * light - 1));
        const hue = (((max === r ? (g - b) / delta : max === g ? (b - r) / delta + 2 : (r - g) / delta + 4) * 60) + 360) % 360;
        if (hue < 23 || hue > 65 || saturation < .12 || light < .3) return token;
        let next;
        if (property === 'color' || property === 'fill' || property === 'stroke' || ['--color-primary', '--mf-accent', '--mf-accent-hover'].includes(property)) next = [180, 25, 53];
        else if (property.includes('shadow')) next = [197, 30, 60];
        else if (property.includes('border') || property.includes('outline')) next = light > .85 ? [242, 218, 225] : [226, 153, 169];
        else if (light > .96) next = [255, 250, 251];
        else if (light > .90) next = [255, 241, 245];
        else if (light > .80) next = [255, 226, 234];
        else next = [250, 210, 221];
        return alpha < 1 ? `rgba(${next.join(', ')}, ${alpha})` : `rgb(${next.join(', ')})`;
      });
    }
    function rules(list) {
      return [...list].map(rule => {
        if (rule.type === CSSRule.STYLE_RULE) {
          const changed = [...rule.style].flatMap(property => {
            if (/--mf-(face|skin|eyes|box|custom)-color/.test(property)) return [];
            const value = rule.style.getPropertyValue(property), next = convert(value, property);
            return next === value ? [] : [`  ${property}: ${next}${rule.style.getPropertyPriority(property) ? ' !important' : ''};`];
          });
          return changed.length ? `${rule.selectorText} {\n${changed.join('\n')}\n}` : '';
        }
        if (rule.cssRules) {
          const children = rules(rule.cssRules);
          return children ? `${rule.cssText.slice(0, rule.cssText.indexOf('{'))}{\n${children}\n}` : '';
        }
        return '';
      }).filter(Boolean).join('\n');
    }
    return sources.map(({ path, css }) => {
      const sheet = new CSSStyleSheet(); sheet.replaceSync(css);
      return `/* ${path} */\n${rules(sheet.cssRules)}`;
    }).join('\n\n');
  }, paths.map(path => ({ path, css: fs.readFileSync(path, 'utf8').replace(/^\uFEFF/, '') })));
  fs.writeFileSync('css/apex-theme.css', '/* Generated by node scripts/build-apex-theme.js. Color overrides only. */\n' + output + '\n');
  console.log('Apex red/rose theme generated.');
} finally { await browser.close(); }
